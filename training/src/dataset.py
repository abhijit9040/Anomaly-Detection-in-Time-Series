"""
PyTorch Dataset for Time-Series Anomaly Detection.

Wraps the numpy sliding windows generated by the preprocessing pipeline
into a PyTorch Dataset for use with DataLoaders.
"""

from __future__ import annotations

import torch
from torch.utils.data import Dataset

class TimeSeriesDataset(Dataset):
    """
    Standard PyTorch Dataset for sequence data.
    """
    def __init__(self, windows: torch.Tensor | np.ndarray):
        """
        Args:
            windows: Array of shape (n_samples, window_size, n_features)
        """
        if not isinstance(windows, torch.Tensor):
            self.windows = torch.tensor(windows, dtype=torch.float32)
        else:
            self.windows = windows.float()

    def __len__(self) -> int:
        return len(self.windows)

    def __getitem__(self, idx: int) -> torch.Tensor:
        """
        Returns a single window.
        Since this is an Autoencoder, the input is also the target.
        """
        return self.windows[idx]
